test('sticky content grows in both dimensions while preserving typed text and manual resizing', async ({ page }) => {
  page.setDefaultTimeout(8000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(url)
  await page.getByLabel('New board', { exact: true }).fill('Growing ideas')
  await page.getByLabel('Board template').selectOption('blank')
  await page.getByRole('button', { name: 'Create board', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Saved locally')
  const boardId = new URL(page.url()).searchParams.get('board')
  await page.getByRole('button', { name: 'Sticky note', exact: true }).click()
  await page.getByRole('textbox', { name: 'Sticky note text', exact: true }).fill('An idea')
  await page.getByRole('button', { name: 'Add sticky note', exact: true }).click()
  await expect.poll(() => app.store.read(boardId).elements.length).toBe(2)
  const noteId = app.store.read(boardId).elements.find(e => e.type === 'rectangle').id
  const initial = app.store.read(boardId).elements.find(e => e.id === noteId)
  const canvas = page.locator('.excalidraw canvas').last()
  const bounds = await canvas.boundingBox()
  await page.mouse.dblclick(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  const longIdea = 'Explore how the system connects people, ideas and useful experiments. '.repeat(12)
  const editor = page.locator('.excalidraw-wysiwyg')
  await editor.fill(longIdea)
  await expect.poll(() => app.store.read(boardId).elements.find(e => e.id === noteId)?.width).toBeGreaterThan(240)
  await editor.press('End')
  await editor.pressSequentially(' Next test.')
  await page.keyboard.press('Escape')
  await expect.poll(() => app.store.read(boardId).elements.find(e => e.containerId === noteId)?.originalText).toContain('Next test.')
  await expect.poll(() => { const note = app.store.read(boardId).elements.find(e => e.id === noteId); return note.height / note.width }).toBeLessThanOrEqual(1.15)
  const grown = app.store.read(boardId).elements.find(e => e.id === noteId)
  expect(grown.height).toBeGreaterThan(155)
  expect(grown.height / grown.width).toBeLessThanOrEqual(1.15)
  expect(app.store.read(boardId).elements.find(e => e.containerId === noteId).fontSize).toBe(20)
  // Resize the selected note using its native bottom-right handle.
  await page.mouse.move(bounds.x + bounds.width / 2 - initial.width / 2 + grown.width, bounds.y + bounds.height / 2 - initial.height / 2 + grown.height)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width / 2 - initial.width / 2 + grown.width + 50, bounds.y + bounds.height / 2 - initial.height / 2 + grown.height + 30, { steps: 5 })
  await page.mouse.up()
  await expect.poll(() => app.store.read(boardId).elements.find(e => e.id === noteId)?.width).toBeGreaterThan(grown.width + 20)
  await page.getByRole('button', { name: 'Sticky note', exact: true }).click()
  await page.getByRole('textbox', { name: 'Sticky note text', exact: true }).fill(longIdea)
  await page.getByRole('button', { name: 'Add sticky note', exact: true }).click()
  await expect.poll(() => app.store.read(boardId).elements.filter(e => e.type === 'rectangle').length).toBe(2)
  const createdLong = app.store.read(boardId).elements.find(e => e.type === 'rectangle' && e.id !== noteId)
  expect(createdLong.width).toBeGreaterThan(240)
  expect(createdLong.height / createdLong.width).toBeLessThanOrEqual(1.15)
  await page.screenshot({ path: '.tmp/sticky-growth.png' })
  expect(errors).toEqual([])
})

test('board menu collapses and thinking panel resizes, remembers width and remains hideable', async ({ page }) => {
  await page.goto(url)
  await page.getByLabel('New board', { exact: true }).fill('Room to think')
  await page.getByLabel('Board template').selectOption('blank')
  await page.getByRole('button', { name: 'Create board', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Saved locally')
  const nav = page.getByRole('navigation', { name: 'Saved boards', includeHidden: true })
  await expect(nav).not.toBeVisible()
  const canvas = page.getByTestId('canvas')
  const fullWidth = (await canvas.boundingBox()).width
  const menu = page.getByRole('button', { name: 'Toggle boards', exact: true })
  await menu.click()
  await expect(nav).toBeVisible()
  await expect(menu).toHaveAttribute('aria-expanded', 'true')
  expect((await canvas.boundingBox()).width).toBeLessThan(fullWidth - 150)
  await menu.click()
  await expect(nav).not.toBeVisible()
  const panel = page.getByRole('complementary', { name: 'Thinking tools' })
  const initialWidth = (await panel.boundingBox()).width
  const handle = page.getByRole('separator', { name: 'Resize thinking panel' })
  const bounds = await handle.boundingBox()
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width / 2 - 100, bounds.y + bounds.height / 2, { steps: 5 })
  await page.mouse.up()
  await expect.poll(async () => (await panel.boundingBox()).width).toBeCloseTo(initialWidth + 100)
  await handle.focus()
  await handle.press('ArrowRight')
  await expect.poll(async () => (await panel.boundingBox()).width).toBeCloseTo(initialWidth + 80)
  await page.getByRole('button', { name: 'Hide panel', exact: true }).click()
  await expect(panel).toHaveCount(0)
  await page.getByRole('button', { name: 'Open panel', exact: true }).click()
  await expect.poll(async () => (await panel.boundingBox()).width).toBeCloseTo(initialWidth + 80)
  await page.reload()
  await expect(panel).toBeVisible()
  await expect.poll(async () => (await panel.boundingBox()).width).toBeCloseTo(initialWidth + 80)
  await handle.focus()
  await handle.press('Home')
  await expect.poll(async () => (await panel.boundingBox()).width).toBeCloseTo(240)
  await handle.press('End')
  await expect.poll(async () => (await panel.boundingBox()).width).toBeCloseTo(640)
  await page.screenshot({ path: '.tmp/sidebar-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect((await panel.boundingBox()).width).toBeLessThan(390)
  await page.getByRole('button', { name: 'Hide panel', exact: true }).click()
  await menu.click()
  await expect(nav).toBeVisible()
  await page.screenshot({ path: '.tmp/sidebar-mobile.png' })
  await menu.click()
  await expect(nav).not.toBeVisible()
})
